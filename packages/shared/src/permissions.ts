/** Existing roles that may create clients. There is no Sales role in FalconV. */
export const CLIENT_CREATE_ROLES = ['super_admin', 'admin', 'csm'] as const;

export function canCreateClient(roles: readonly string[], permissions: readonly string[]) {
  return (
    permissions.includes('clients.write') &&
    roles.some((role) => (CLIENT_CREATE_ROLES as readonly string[]).includes(role))
  );
}
